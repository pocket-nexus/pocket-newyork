#!/usr/bin/env bun
/**
 * Compiles the interface (`ui/`, one PocketJS app) for a device. PocketJS resolves `ui/pocket.json` against the
 * device's profile, picks the presentation its modality asks for and writes the bundle and its pak.
 *
 *   bun tools/ui.ts <vita|psp>          → .pocket-build/ui/<device>/newyork.{js,pak}, plan.json
 *   bun tools/ui.ts prepare [device]    → what the interface compiles from the reference (ui/app/generated/)
 *   bun tools/ui.ts preview [device…]   → pictures of every screen, .pocket-build/ui/preview/
 *   bun tools/ui.ts test [device…]      → the interface driven through a mock renderer
 *
 * What it compiles from is the export's (`bun tools/newyork.ts export --only world` and `--only map`):
 * `world.json` (the places, the cameras), `interface.json` (the modes and the hours as the reference's HUD names
 * them, and where its map lies) and `map.png` (the reference's own atlas of the island).
 */
import { existsSync, mkdirSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { extractHostBuildInputs, type HostBuildInputs } from "../vendor/pocketjs/framework/src/manifest/index.ts";
import { createCanvas, loadImage } from "../vendor/pocketjs/node_modules/@napi-rs/canvas";

export const DEVICES = ["vita", "psp"] as const;
export type Device = (typeof DEVICES)[number];

const root = resolve(import.meta.dir, "..");
const pocket = join(root, "vendor/pocketjs");
const project = join(root, "ui");
const manifest = join(project, "pocket.json");
const generated = join(project, "app/generated");
const ir = join(root, ".pocket-build/scene/ir");

export interface Interface {
  /** Directory holding `newyork.js`, `newyork.pak` and `plan.json`. */
  directory: string;
  inputs: HostBuildInputs;
  plan: { features: Record<string, boolean> };
}

function run(args: string[], cwd = pocket) {
  const done = Bun.spawnSync(args, { cwd, stdout: "inherit", stderr: "inherit" });
  if (done.exitCode !== 0) throw new Error(`ui: ${args.slice(0, 3).join(" ")} failed`);
}

/** The two pictures of the island the interface keeps: the menu's, at one texel a logical pixel, and the one in
 *  play's corner. A pak image is a square of a power of two: the map stands at its top left. `tall` is the map's
 *  height in logical pixels. */
const PICTURES = [
  { name: "map", texture: 256, tall: 232 },
  { name: "map-small", texture: 128, tall: 124 },
] as const;

/**
 * Writes what the interface compiles from the reference (`ui/app/generated/`, ignored): the names of its modes,
 * hours, cameras and places, and its map of the island reduced to the device's pictures.
 */
export async function prepareInterface(device: Device = "vita"): Promise<void> {
  const need = ["world.json", "interface.json", "map.png"].map((name) => join(ir, name));
  for (const file of need) if (!existsSync(file)) throw new Error(`ui: ${file} is missing: run \`bun tools/newyork.ts export --only world\` and \`--only map\``);
  const world = await Bun.file(need[0]).json();
  const face = await Bun.file(need[1]).json();
  mkdirSync(generated, { recursive: true });

  // The Vita rasters two samples per logical pixel.
  const density = device === "vita" ? 2 : 1;
  const source = face.map as { x0: number; z0: number; metresPerPixel: number; width: number; height: number };
  const maps: Record<string, unknown> = {};
  for (const p of PICTURES) {
    const scale = p.tall / source.height;
    const width = Math.round(source.width * scale), height = p.tall;
    const metres = source.metresPerPixel / scale;
    maps[p.name] = { image: `generated/${p.name}.png`, texture: p.texture, width, height, x0: source.x0, z0: source.z0, metres };
    const file = join(generated, `${p.name}.png`);
    const stamp = join(generated, `.${p.name}-${density}`);
    if (existsSync(file) && existsSync(stamp) && statSync(stamp).mtimeMs >= statSync(need[2]).mtimeMs) continue;
    const canvas = createCanvas(p.texture * density, p.texture * density);
    const ctx = canvas.getContext("2d");
    // The rest of the square stays clear: an image is drawn whole, and nothing clips it.
    ctx.imageSmoothingEnabled = true;
    ctx.imageSmoothingQuality = "high";
    ctx.drawImage(await loadImage(need[2]), 0, 0, width * density, height * density);
    for (const old of new Bun.Glob(`.${p.name}-*`).scanSync({ cwd: generated, dot: true })) await Bun.file(join(generated, old)).delete();
    writeFileSync(file, canvas.toBuffer("image/png"));
    writeFileSync(stamp, "");
  }

  const pick = <K extends string>(list: Record<string, unknown>[], keys: K[]) => list.map((item) => Object.fromEntries(keys.map((k) => [k, item[k]])));
  writeFileSync(join(generated, "world.ts"), `// Generated by tools/ui.ts from the reference's export (world.json, interface.json, map.png).
import type { Player } from "../protocol.ts";

/** The four ways through the city, in ny_sim's order: the reference's button name, what its HUD calls the player,
 *  and the top of its speed meter in miles an hour. */
export const MODES: { id: Player; name: string; label: string; topMph: number }[] = ${JSON.stringify(face.modes, null, 2)};

/** The reference's hours, in ny_sim's order. */
export const HOURS: { id: string; name: string; time: string; short: string }[] = ${JSON.stringify(face.hours, null, 2)};

/** The reference's cameras (CAMERA_PRESETS): the first ones follow the player. */
export const CAMERAS: { id: string; name: string; short: string; category: string }[] = ${JSON.stringify(pick(world.cameras, ["id", "name", "short", "category"]), null, 2)};

/** The reference's teleports, in index.html's order, in the city's metres. */
export const PLACES: { id: string; name: string; sub: string; x: number; z: number }[] = ${JSON.stringify(pick(world.places, ["id", "name", "sub", "x", "z"]), null, 2)};

/** A picture of the island: a square of \`texture\` logical pixels with the map, \`width\` × \`height\`, at its top
 *  left; the city's metres at the map's left and top edges, and per logical pixel. Grid north is up. */
export interface MapPicture { image: string; texture: number; width: number; height: number; x0: number; z0: number; metres: number }
export const MAP: MapPicture = ${JSON.stringify(maps.map)};
export const SMALL_MAP: MapPicture = ${JSON.stringify(maps["map-small"])};
`);
  writeFileSync(join(project, "app/images.json"), JSON.stringify(Object.fromEntries(PICTURES.map((p) => [`generated/${p.name}.png`, { linear: true }])), null, 2) + "\n");
}

export async function compileInterface(device: Device): Promise<Interface> {
  await prepareInterface(device);
  const directory = join(root, ".pocket-build/ui", device);
  mkdirSync(directory, { recursive: true });
  const planPath = join(directory, "plan.json");
  run(["bun", "tools/pocket.ts", "compile", "--target", device, "--manifest", manifest, "--project-root", project, "--outdir", directory]);
  await Bun.write(planPath, Bun.file(join(project, ".pocket", device, "plan.json")));
  const plan = await Bun.file(planPath).json();
  return { directory, plan, inputs: extractHostBuildInputs(plan) };
}

if (import.meta.main) {
  const [command, ...rest] = process.argv.slice(2);
  if (command === "prepare") await prepareInterface((rest[0] as Device) ?? "vita");
  else if (command === "preview" || command === "test") {
    // Both run the bundle on PocketJS's UI core built for wasm.
    if (!existsSync(join(pocket, "hosts/web/pocketjs.wasm"))) run(["bun", "tools/wasm.ts"]);
    // One process per device: a bundle owns `globalThis.frame`.
    for (const device of rest.length ? (rest as Device[]) : (["vita"] as Device[])) {
      await compileInterface(device);
      run(["bun", `ui/test/${command === "test" ? "flow" : "preview"}.ts`, device], root);
    }
  } else if (DEVICES.includes(command as Device)) {
    const built = await compileInterface(command as Device);
    console.log(`${command}: ${built.inputs.target}, ${built.inputs.viewport.logical.join("×")} @${built.inputs.viewport.rasterDensity}x → ${built.directory}`);
  } else throw new Error(`usage: bun tools/ui.ts <${DEVICES.join("|")}|prepare [device]|preview [device…]|test [device…]>`);
}
